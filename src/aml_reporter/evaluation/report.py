"""Render an evaluation run as Markdown: the content of `docs/evaluation.md`."""

from .details import class_sections, rejection_section
from .markdown import SUBSETS, TASK_NAMES, pct, table
from .models import CaseOutcome, EvaluationRun


def _summary(run: EvaluationRun) -> list[str]:
    """Build the overview: volume, LLM share, speed, cost, and end-to-end result.

    Args:
        run: Evaluation run.

    Returns:
        Section lines.
    """
    header = ["Enricher", "Model", "From the LLM", "Seconds / 1,000", "USD / 1,000", "Cases right"]
    rows = [
        [
            e.enricher,
            f"`{e.model}`",
            pct(e.llm_share),
            f"{e.per_thousand(e.seconds):,.1f}",
            "–" if e.cost_usd is None else f"{e.per_thousand(e.cost_usd):.4f}",
            f"{sum(case.correct for case in e.cases)} / {len(e.cases)}",
        ]
        for e in run.enrichers
    ]
    return ["## Summary", "", *table(header, rows, left=2)]


def _accuracy(run: EvaluationRun) -> list[str]:
    """Build the accuracy table: every task on all, easy, and hard descriptions.

    Args:
        run: Evaluation run.

    Returns:
        Section lines.
    """
    header = ["Task", "Descriptions", *[e.enricher for e in run.enrichers]]
    rows = [
        [
            f"{TASK_NAMES[task]}, {subset}",
            run.enrichers[0].score(task, subset).items,
            *[pct(e.score(task, subset).accuracy) for e in run.enrichers],
        ]
        for task in TASK_NAMES
        for subset in SUBSETS
    ]
    intro = (
        "Share of descriptions where the field equals the label exactly; names ignore case and "
        "spacing, and an empty field is right when the label is empty too."
    )
    return ["## Accuracy", "", intro, "", *table(header, rows)]


def _errors(run: EvaluationRun) -> list[str]:
    """Build the table of missed and invented values, on all descriptions.

    Args:
        run: Evaluation run.

    Returns:
        Section lines.
    """
    header = ["Task"]
    for e in run.enrichers:
        header += [f"{e.enricher}: missed", f"{e.enricher}: invented"]
    rows = []
    for task in TASK_NAMES:
        row: list[object] = [TASK_NAMES[task]]
        for e in run.enrichers:
            score = e.score(task)
            row += [pct(score.missed), pct(score.invented)]
        rows.append(row)
    intro = (
        "*Missed*: the label has a value, the enricher none (`null`, or `unknown` for the "
        "purpose). *Invented*: the label has none, the enricher gives one."
    )
    return ["## Missed and invented values", "", intro, "", *table(header, rows)]


def _verdict(case: CaseOutcome) -> str:
    """Summarise one end-to-end result.

    Args:
        case: Outcome of one case.

    Returns:
        A check mark, or what went wrong.
    """
    if case.correct:
        return "✓"
    return f"✗ {case.level}: {', '.join(case.raised_flags) or 'no flags'}"


def _cases(run: EvaluationRun) -> list[str]:
    """Build the end-to-end table: red flags and risk level of every case.

    Args:
        run: Evaluation run.

    Returns:
        Section lines.
    """
    header = ["Scenario", "Expected", *[e.enricher for e in run.enrichers]]
    rows = [
        [
            f"`{case.scenario}`",
            f"{case.expected_level}: {', '.join(case.expected_flags) or 'no flags'}",
            *[_verdict(e.cases[index]) for e in run.enrichers],
        ]
        for index, case in enumerate(run.enrichers[0].cases)
    ]
    intro = (
        "A case is right when it raises exactly the expected flags and reaches the expected level."
    )
    return ["## Red flags and risk level", "", intro, "", *table(header, rows, left=len(header))]


def render(run: EvaluationRun) -> str:
    """Render the whole report.

    Args:
        run: Evaluation run.

    Returns:
        Markdown text.
    """
    options = " ".join(f"--enricher {e.enricher}" for e in run.enrichers)
    items = run.enrichers[0].score("iban").items
    lines = [
        "# Evaluation",
        "",
        f"Generated by `uv run aml-report evaluate {options}` on "
        f"{run.generated_at:%Y-%m-%d}, from the synthetic cases in `{run.dataset}`: "
        f"{len(run.enrichers[0].cases)} cases, {items} descriptions, {run.hard_items} of them "
        "hard (heavy noise). Labels come from the generator, never from a model. Timings depend "
        "on the machine; costs use list prices.",
        "",
        *_summary(run),
        *_accuracy(run),
        *_errors(run),
        *class_sections(run),
        *_cases(run),
        *rejection_section(run),
    ]
    return "\n".join(lines).rstrip() + "\n"
